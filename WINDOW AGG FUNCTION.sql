# QUES: FIND THE DEVIATION FROM THE MAX AND MIN TOTAL SALES/BILLS

SELECT
TOTAL, CUSTOMERID, BILLINGCOUNTRY,
MIN(TOTAL) OVER(PARTITION BY BILLINGCOUNTRY) MINTOTALAMNT,
MAX(TOTAL) OVER(PARTITION BY BILLINGCOUNTRY) MAXTOTALAMNT,
TOTAL - MIN(TOTAL) OVER() AS DEVFROM_MIN,
MAX(TOTAL) OVER() - TOTAL AS DEVFROM_MAX 
 FROM INVOICE;
							
####### RUNNING AND ROLLING TOTAL #########
# RUNNING TOTAL GOOD FOR TRACKING BUDGET, CURRENT TOTAL SALES WITH TARGET
# ROLLING TOTAL GOOD FOR SPECIFIC OUTPUT FROM TIME FRAME OR OTHER VARIABLES, GOOD FOR FOCUSED ANALYSIS
# ques: CALCULATE THE MOVING AVG OF TOTAL BILL OVER THE TIME, INCLUDING ONLY THE NEXT TOTAL OR BILL

SELECT 
BILLINGCOUNTRY, CUSTOMERID, TOTAL, 
ROUND(AVG(TOTAL) OVER(PARTITION BY BILLINGCOUNTRY ORDER BY CUSTOMERID), 2) AS RUNNING_TOTAL  #--USES DEFAULT UNBOUNDED ROWS
FROM INVOICE;

SELECT 
BILLINGCOUNTRY, CUSTOMERID, TOTAL, 
ROUND(AVG(TOTAL) OVER(PARTITION BY BILLINGCOUNTRY ORDER BY CUSTOMERID ROWS BETWEEN 2 PRECEDING AND CURRENT ROW ), 2) AS ROLLING_TOTAL 
FROM INVOICE;

# ques: CALCULATE THE MOVING AVG OF TOTAL BILL OVER THE TIME, INCLUDING ONLY THE NEXT TOTAL OR BILL
# UNITIN BOTH QUERRIES WE GET :
SELECT 
BILLINGCOUNTRY, CUSTOMERID, TOTAL, 
ROUND(AVG(TOTAL) OVER(PARTITION BY BILLINGCOUNTRY ORDER BY CUSTOMERID), 2) AS RUNNING_TOTAL,  #--USES DEFAULT UNBOUNDED ROWS
ROUND(AVG(TOTAL) OVER(PARTITION BY BILLINGCOUNTRY ORDER BY CUSTOMERID ROWS BETWEEN 2 PRECEDING AND CURRENT ROW ), 2) AS ROLLING_TOTAL,
ROUND(AVG(TOTAL) OVER(PARTITION BY BILLINGCOUNTRY ORDER BY CUSTOMERID ROWS BETWEEN CURRENT ROW AND 1 FOLLOWING ), 2) AS NEXTINCL_MOVING_AVG 
FROM INVOICE;
