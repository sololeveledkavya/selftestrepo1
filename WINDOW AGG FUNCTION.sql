# QUES: SEE THE PERCENTAGE OF CONTRIBUTION OF EACH CUSTOMER
SELECT 
CUSTOMERID,
BILLINGCOUNTRY,
TOTAL,
SUM(TOTAL) OVER() TOTALSALES,
SUM(TOTAL) OVER(PARTITION BY BILLINGCOUNTRY ORDER BY TOTAL) AS TOTALAMNT,
ROUND(CAST(TOTAL AS FLOAT) / SUM(TOTAL) OVER() * 100, 2) AS PERCENTSHARE
FROM INVOICE
ORDER BY PERCENTSHARE DESC;


