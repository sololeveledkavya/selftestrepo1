SELECT * FROM (
    SELECT 
        FirstName, 
        LastName, 
        Company, 
        State,
        -- This counts how many customers are in the same state
        COUNT(CustomerId) OVER(PARTITION BY State) AS state_count,
        CONCAT(FirstName, ' ', LastName) AS FullName
    FROM customer
) AS customer_subquery
WHERE state_count > 1; -- Use the name you created inside!

# QUES:  CUSTOMER WITH SAME CUSTOMER NAME
SELECT 
    FirstName, 
    LastName, 
    COUNT(*) AS occurrence_count
FROM customer
GROUP BY FirstName, LastName
HAVING COUNT(*) > 1;

# QUES: FIND SAME NAME LAST NAMES CUSTOMERS (USING EACH ROW) 
SELECT * FROM (
    SELECT 
        CustomerId, 
        FirstName, 
        LastName,
        COUNT(*) OVER(PARTITION BY FirstName, LastName) AS name_occurrence
    FROM customer
) AS sub
WHERE name_occurrence > 1
ORDER BY LastName, FirstName;

# QUES: "Some customers might have accidental spaces at the beginning or end of their names. 
#       --Write a query using a subquery to find any duplicate name pairs after cleaning up 
#       --those extra spaces."
SELECT 
CLEANFIRSTNAME,
CLEANLASTNAME, 
COUNT(*) AS OCCURRENCE_COUNT
FROM
  (  
  SELECT
	TRIM(FirstName) AS CleanFirstName, 
	TRIM(LastName) AS CleanLastName, 
    COUNT(*) 
FROM customer
GROUP BY CleanFirstName, CleanLastName
HAVING COUNT(*) > 1
) 
AS SUB
GROUP BY CLEANFIRSTNAME, CLEANLASTNAME
HAVING COUNT(*) > 1;


